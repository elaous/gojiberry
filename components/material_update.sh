#!/bin/sh
# Regenerates material_data.go from the Material Symbols (outlined, weight 400) SVGs
# published on npm as @material-symbols/svg-400 (Apache License 2.0). Needs network.
# Usage: sh components/material_update.sh   (from the repository root)
set -e
names="fact_check abc account_circle find_replace format_quote format_size add add_comment add_photo_alternate bookmark bookmark_add check checklist close comment content_copy content_paste create_new_folder dashboard_customize delete delete_forever description design_services download draw edit expand_more extension folder folder_open format_align_center format_align_justify format_align_left format_align_right format_bold format_clear format_color_fill format_color_reset format_color_text format_indent_decrease format_indent_increase format_italic format_list_bulleted format_list_numbered format_paint format_underlined functions grid_view history id input ios_share key keyboard keyboard_tab language layers_clear link lock margin more_vert note_add numbers picture_as_pdf print redo refresh restore_from_trash search sell settings share spellcheck strikethrough_s style subscript superscript table text_fields title toc tune undo upload_file view_agenda wallpaper"
out=components/material_data.go
{
  echo "// Code generated by material_update.sh; DO NOT EDIT."
  echo "//"
  echo "// The icons are Google's Material Symbols (outlined, weight 400), licensed under the"
  echo "// Apache License 2.0 (https://www.apache.org/licenses/LICENSE-2.0). Each value is the"
  echo "// path of a 960x960 icon whose viewBox is \"0 -960 960 960\"."
  echo
  echo "package components"
  echo
  echo "var materialPaths = map[string]string{"
  for n in $names; do
    d=$(curl -fsS --retry 3 --retry-all-errors "https://cdn.jsdelivr.net/npm/@material-symbols/svg-400/outlined/$n.svg" | sed -n 's/.*<path d="\([^"]*\)".*/\1/p') || d=""
    [ -n "$d" ] || { echo "skipping $n: no such icon" >&2; continue; }
    echo "	\"$n\": \"$d\","
  done
  echo "}"
} > "$out"
gofmt -w "$out"
